package org.rsmod.tools.wiki.dumping

import java.nio.file.Files
import java.nio.file.Path
import org.rsmod.content.slayer.core.CanonicalSlayerRegistry

fun main(args: Array<String>) {
    val projectRoot = args.firstOrNull()?.let(Path::of) ?: Path.of("").toAbsolutePath()
    val output = projectRoot.resolve("docs/slayer/canonical-regular-slayer.md")
    Files.createDirectories(output.parent)
    Files.writeString(output, CanonicalSlayerWikiExporter.render())
    println("Canonical Slayer wiki exported: $output")
}

object CanonicalSlayerWikiExporter {
    fun render(): String = buildString {
        appendLine("# Canonical Regular Slayer Roster")
        appendLine()
        appendLine("Generated from `CanonicalSlayerRegistry`. Do not edit this file by hand.")
        appendLine()
        appendLine("- Enabled regular master: Krystilia (master ID 7)")
        appendLine("- Assignment UI: one Wilderness boss, one Edgeville Dungeon task, one Custom Slayer Cave task")
        appendLine("- Future out-of-Wilderness boss service: disabled; allowlist empty; quantity 3-5")
        appendLine("- Kill credit: exact NPC ID plus authorized dead-NPC location")
        appendLine()
        appendLine("| ID | Key | Display | NPC IDs | Authorized locations | Slayer | Quantity | Weight | Boss | Teleport | Aliases / exclusions |")
        appendLine("|---:|---|---|---|---|---:|---:|---:|:---:|---|---|")
        for (category in CanonicalSlayerRegistry.categories) {
            append("| ")
            append(category.id)
            append(" | ")
            append(category.key)
            append(" | ")
            append(category.displayName)
            append(" | ")
            append(category.npcIds.joinToString())
            append(" | ")
            append(category.locations.joinToString { locationName(it) })
            append(" | ")
            append(category.slayerRequirement)
            append(" | ")
            append(category.minAmount)
            append('-')
            append(category.maxAmount)
            append(" | ")
            append(category.weight)
            append(" | ")
            append(if (category.boss) "yes" else "no")
            append(" | ")
            append("Beside an active authorized ")
            append(category.displayName)
            append(" spawn")
            append(" | ")
            append(aliasNote(category.id))
            appendLine(" |")
        }
    }

    private fun locationName(location: CanonicalSlayerRegistry.Location): String =
        when (location) {
            CanonicalSlayerRegistry.Location.Wilderness -> "Wilderness"
            CanonicalSlayerRegistry.Location.EdgevilleDungeon -> "Edgeville Dungeon"
            CanonicalSlayerRegistry.Location.CustomSlayerCave -> "Custom Slayer Cave"
            CanonicalSlayerRegistry.Location.KingBlackDragon -> "King Black Dragon lair"
            CanonicalSlayerRegistry.Location.CorporealBeast -> "Corporeal Beast lair"
        }

    private fun aliasNote(categoryId: Int): String =
        when (categoryId) {
            41 -> "Revenant Maledictus is a directed valid kill alias."
            52 -> "Superior Venator is a directed valid kill alias; it is not independently assignable."
            59 -> "Callisto only; Artio excluded."
            60 -> "Artio only; Callisto excluded."
            61 -> "Vet'ion forms only; Calvar'ion excluded."
            62 -> "Calvar'ion forms only; Vet'ion excluded."
            63 -> "Venenatis only; Spindel excluded."
            64 -> "Spindel only; Venenatis excluded."
            69 -> "Revenant Maledictus only; ordinary Revenants excluded."
            else -> "Exact listed IDs only."
        }
}
